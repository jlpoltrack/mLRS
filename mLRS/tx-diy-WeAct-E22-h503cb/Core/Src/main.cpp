/**
  * @brief System Clock Configuration
  * @retval None
  *
  * WeAct STM32H503Cx core board: 8 MHz HSE crystal (Y2).
  * PLL1: 8 MHz / M=2 = 4 MHz -> x N=125 -> VCO 500 MHz -> /P=2 = 250 MHz SYSCLK.
  * PLL1Q = 250 MHz, which is the default kernel clock of SPI1/2/3, and which is
  * what the stm32ll-lib SPI baudrate table for H5 assumes.
  * HCLK = PCLK1 = PCLK2 = PCLK3 = 250 MHz. VOS0 and 5 flash wait states are
  * required at 250 MHz.
  */
void SystemClock_Config(void)
{
  RCC_OscInitTypeDef RCC_OscInitStruct = {0};
  RCC_ClkInitTypeDef RCC_ClkInitStruct = {0};

  /** Configure the main internal regulator output voltage
  */
  if (HAL_PWREx_ControlVoltageScaling(PWR_REGULATOR_VOLTAGE_SCALE0) != HAL_OK)
  {
    Error_Handler();
  }

  /** Initializes the RCC Oscillators according to the specified parameters
  * in the RCC_OscInitTypeDef structure.
  */
  RCC_OscInitStruct.OscillatorType = RCC_OSCILLATORTYPE_HSE;
  RCC_OscInitStruct.HSEState = RCC_HSE_ON;
  RCC_OscInitStruct.PLL.PLLState = RCC_PLL_ON;
  RCC_OscInitStruct.PLL.PLLSource = RCC_PLL1_SOURCE_HSE;
  RCC_OscInitStruct.PLL.PLLM = 2;
  RCC_OscInitStruct.PLL.PLLN = 125;
  RCC_OscInitStruct.PLL.PLLP = 2;
  RCC_OscInitStruct.PLL.PLLQ = 2;
  RCC_OscInitStruct.PLL.PLLR = 2;
  RCC_OscInitStruct.PLL.PLLRGE = RCC_PLL1_VCIRANGE_2;
  RCC_OscInitStruct.PLL.PLLVCOSEL = RCC_PLL1_VCORANGE_WIDE;
  RCC_OscInitStruct.PLL.PLLFRACN = 0;
  if (HAL_RCC_OscConfig(&RCC_OscInitStruct) != HAL_OK)
  {
    Error_Handler();
  }

  /** Initializes the CPU, AHB and APB buses clocks
  */
  RCC_ClkInitStruct.ClockType = RCC_CLOCKTYPE_HCLK|RCC_CLOCKTYPE_SYSCLK
                              |RCC_CLOCKTYPE_PCLK1|RCC_CLOCKTYPE_PCLK2
                              |RCC_CLOCKTYPE_PCLK3;
  RCC_ClkInitStruct.SYSCLKSource = RCC_SYSCLKSOURCE_PLLCLK;
  RCC_ClkInitStruct.AHBCLKDivider = RCC_SYSCLK_DIV1;
  RCC_ClkInitStruct.APB1CLKDivider = RCC_HCLK_DIV1;
  RCC_ClkInitStruct.APB2CLKDivider = RCC_HCLK_DIV1;
  RCC_ClkInitStruct.APB3CLKDivider = RCC_HCLK_DIV1;

  if (HAL_RCC_ClockConfig(&RCC_ClkInitStruct, FLASH_LATENCY_5) != HAL_OK)
  {
    Error_Handler();
  }

  /* The flash signal delay (FLASH_ACR.WRHIGHFREQ) is NOT touched by
     HAL_RCC_ClockConfig(), but it must match the flash clock or programming the
     flash becomes unreliable. At 250 MHz that is FLASH_PROGRAMMING_DELAY_2
     (168 MHz .. 250 MHz). Without this the emulated eeprom, i.e. storing the
     setup, binding, and the powerup counter, can silently fail. */
  __HAL_FLASH_SET_PROGRAM_DELAY(FLASH_PROGRAMMING_DELAY_2);
}

/**
  * @brief Peripherals Common Clock Configuration
  * @retval None
  *
  * The SPI kernel clock is NOT derived from PCLK on H5: SPI1 can only be fed from
  * PLL1Q, PLL2P, PLL3P, an external pin, or CLKP. It defaults to PLL1Q, but
  * HAL_RCC_OscConfig() enables only the PLL1P output, so PLL1Q stays switched off
  * and SPI1 would have no kernel clock at all. The master then never generates SCK
  * and the very first transfer hangs forever waiting for RXP.
  * Selecting PLL1Q here also enables that PLL output. PLL1Q = VCO/PLLQ = 500/2 =
  * 250 MHz, which is the kernel clock the stm32ll-lib H5 baudrate table assumes.
  * The radio is on SPI1, see the hal. If it is ever moved back to SPI2, this has
  * to follow, selecting the wrong one leaves the bus without a kernel clock.
  */
void PeriphCommonClock_Config(void)
{
  RCC_PeriphCLKInitTypeDef PeriphClkInitStruct = {0};

  PeriphClkInitStruct.PeriphClockSelection = RCC_PERIPHCLK_SPI1;
  PeriphClkInitStruct.Spi1ClockSelection = RCC_SPI1CLKSOURCE_PLL1Q;
  if (HAL_RCCEx_PeriphCLKConfig(&PeriphClkInitStruct) != HAL_OK)
  {
    Error_Handler();
  }
}

